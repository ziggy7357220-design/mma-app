    return workouts.where((w) => w.martialArt == artId).toList();
  }

  static List<Workout> workoutsByCategory(String artId, String category) {
    return workouts.where((w) => w.martialArt == artId && w.category == category).toList();
  }

  static List<Workout> workoutsByDifficulty(String artId, String difficulty) {
